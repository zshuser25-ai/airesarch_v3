from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

from kvresearch.config import Config
from kvresearch.schema import control_envelope
from kvresearch.util import atomic_write_json, ensure_within, path_ref, sha256_file, sha256_tree


_SNAPSHOT_EXCLUDED_PARTS = {"__pycache__", "build", "dist"}
_SNAPSHOT_SCAFFOLD_LINKS = {"centroids", "models", "scales"}


def _snapshot_status_paths(status: str) -> list[str]:
    """Return stable, file-granular candidate paths from git porcelain.

    ``git status`` normally collapses an untracked directory to ``tests/`` and
    also exposes runtime bytecode generated by smoke/import checks.  Neither is
    a reproducible implementation manifest: the former omits file hashes and
    the latter makes snapshots depend on execution order.
    """
    result: list[str] = []
    for line in status.splitlines():
        if len(line) <= 3:
            continue
        item = line[3:]
        # Rename records use ``old -> new``; the destination is authoritative.
        if " -> " in item:
            item = item.rsplit(" -> ", 1)[1]
        relative = Path(item)
        if (
            item in _SNAPSHOT_SCAFFOLD_LINKS
            or any(part in _SNAPSHOT_EXCLUDED_PARTS for part in relative.parts)
            or relative.suffix == ".pyc"
            or relative.name == "results.jsonl"
        ):
            continue
        result.append(item)
    return sorted(dict.fromkeys(result))


def prepare_workspace(config: Config, run_dir: Path, cycle: str) -> Path:
    cycle_dir = run_dir / "cycles" / cycle
    workspace = ensure_within(cycle_dir / "workspace", run_dir)
    if workspace.exists():
        raise FileExistsError(f"workspace already exists: {workspace}")
    source = Path(config.section("baseline")["source"])
    workspace.mkdir(parents=True)
    shutil.copytree(
        source / "scripts",
        workspace / "scripts",
        copy_function=shutil.copy2,
        ignore=shutil.ignore_patterns("__pycache__", "build", "dist", "*.pyc", "results.jsonl"),
    )
    main_pq = workspace / "scripts" / "modeldb" / "main_pq.py"
    source_text = main_pq.read_text(encoding="utf-8")
    old = 'config.datasets_root = config.root / "datasets"'
    new = 'config.datasets_root = pathlib.Path(os.environ.get("KVRESEARCH_DATASETS_ROOT", str(config.root / "datasets")))'
    if old not in source_text:
        raise RuntimeError("cannot install KVRESEARCH_DATASETS_ROOT integration hook")
    main_pq.write_text(source_text.replace(old, new, 1), encoding="utf-8")
    for name in ("models", "scales", "centroids"):
        __import__("os").symlink(source / name, workspace / name, target_is_directory=True)
    (workspace / "datasets").mkdir()
    model_config = dict(config.section("model"))
    source_config = json.loads(Path(model_config["config"]).read_text(encoding="utf-8"))
    source_config["folder"] = model_config["path"]
    atomic_write_json(workspace / "scripts" / "modeldb" / "configs" / "llama-kvresearch.json", source_config)
    subprocess.run(["git", "init", "-q", str(workspace)], check=True)
    subprocess.run(["git", "-C", str(workspace), "config", "user.email", "kvresearch@local"], check=True)
    subprocess.run(["git", "-C", str(workspace), "config", "user.name", "KVResearch"], check=True)
    subprocess.run(["git", "-C", str(workspace), "add", "scripts"], check=True)
    subprocess.run(["git", "-C", str(workspace), "commit", "-q", "-m", "baseline plus kvresearch integration hook"], check=True)
    return workspace


def snapshot_implementation(config: Config, run_dir: Path, cycle: str, candidate_id: str) -> dict[str, Any]:
    workspace = ensure_within(run_dir / "cycles" / cycle / "workspace", run_dir)
    if not (workspace / ".git").is_dir():
        raise ValueError("candidate workspace is not an initialized Git repository")
    status = subprocess.run(
        ["git", "-C", str(workspace), "status", "--porcelain", "--untracked-files=all"],
        text=True, capture_output=True, check=True,
    ).stdout
    changed = _snapshot_status_paths(status)
    diff = subprocess.run(["git", "-C", str(workspace), "diff", "--binary", "HEAD"], text=True, capture_output=True, check=True).stdout
    file_hashes = {item: sha256_file(workspace / item) for item in changed if (workspace / item).is_file()}
    selection = run_dir / "cycles" / cycle / "selection.json"
    plan = run_dir / "cycles" / cycle / "experiment_plan.json"
    patch_material = diff + "\n" + json.dumps(file_hashes, sort_keys=True)
    artifact = control_envelope(
        "implementation_manifest",
        run_dir.name,
        "kvresearch.workspace",
        [path_ref(selection), path_ref(plan)],
        candidate_id=candidate_id,
        workspace=str(workspace),
        base_hash=subprocess.run(["git", "-C", str(workspace), "rev-parse", "HEAD"], text=True, capture_output=True, check=True).stdout.strip(),
        changed_files=changed,
        file_hashes=file_hashes,
        patch_hash=__import__("hashlib").sha256(patch_material.encode("utf-8")).hexdigest(),
        build_command=[],
        run_entrypoint="scripts.modeldb.main_pq",
        dependencies=[],
        source_tree_sha256=sha256_tree(workspace / "scripts", suffixes=(".py", ".sh", ".json"), excluded=("__pycache__",)),
    )
    atomic_write_json(run_dir / "cycles" / cycle / "implementation_manifest.json", artifact)
    return artifact
